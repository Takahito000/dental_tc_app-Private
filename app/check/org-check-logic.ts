// ---------- 判定ロジック（§4） ----------

export type AxisResult =
  | { kind: "left"; score: number; max: number } // 軸1=属人, 軸2=遠慮
  | { kind: "right"; score: number; max: number } // 軸1=仕組み, 軸2=親切
  | { kind: "pending" }; // 「分からない」2問以上 → 判定保留

// 1軸分（4問）の合計点から左右を判定
// - 4問有効: 満点8 → 5点以上で右側（60% = 4.8）
// - 「分からない」1問: 満点6 → 4点以上で右側（60% = 3.6）
// - 「分からない」2問以上 → 判定保留
export function judgeAxis(scores: AnswerCode[]): AxisResult {
  const valid = scores.filter((s): s is 0 | 1 | 2 => s !== null);
  if (scores.length - valid.length >= 2) return { kind: "pending" };
  const score = valid.reduce<number>((sum, s) => sum + s, 0);
  const max = valid.length * 2;
  const threshold = Math.ceil(max * 0.6);
  return { kind: score >= threshold ? "right" : "left", score, max };
}

export type OrgResult =
  | { kind: "type"; type: 1 | 2 | 3 | 4; axis1: AxisResult; axis2: AxisResult }
  | { kind: "partial"; axis1: AxisResult; axis2: AxisResult };

export function computeResult(axis1: AxisResult, axis2: AxisResult): OrgResult {
  if (axis1.kind !== "pending" && axis2.kind !== "pending") {
    // 属人×遠慮=①, 属人×親切=②, 仕組み×遠慮=③, 仕組み×親切=④
    const type = ((axis1.kind === "left" ? 0 : 2) + (axis2.kind === "left" ? 1 : 2)) as 1 | 2 | 3 | 4;
    return { kind: "type", type, axis1, axis2 };
  }
  return { kind: "partial", axis1, axis2 };
}

